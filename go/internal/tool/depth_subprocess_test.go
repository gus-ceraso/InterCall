// metadataBody renders the canonical decoded semantic body of the chain
// declarations, in the file order given.
func metadataBody(t *testing.T, decls []string) []byte {
	t.Helper()
	f, err := syntax.Parse("body.intercall", []byte(strings.Join(decls, "\n")+"\n"))
	if err != nil {
		t.Fatalf("parsing semantic body: %v", err)
	}
	syntax.AttachDocs(f)
	if err := syntax.Validate(f); err != nil {
		t.Fatalf("validating semantic body: %v", err)
	}
	return syntax.Format(f)
}

// metadataModuleFiles renders the two files of one synthetic module: a
// marked generated file whose rows form a cross-row chain of k
// declarations T0..T{k-1} (every row but the last a slice of the next,
// the last uint8, with exact machine lines) and a provider taking T0.
// The parameter root plus the chain puts the deepest physical
// occurrence at depth 2k.
func metadataModuleFiles(t *testing.T, k int) map[string]string {
	t.Helper()
	decls := []string{fmt.Sprintf("type t%d uint8;", k-1)}
	for i := k - 2; i >= 0; i-- {
		decls = append(decls, fmt.Sprintf("type t%d list t%d;", i, i+1))
	}
	body := metadataBody(t, decls)
	var goTypes strings.Builder
	for i := k - 1; i >= 0; i-- {
		if i == k-1 {
			fmt.Fprintf(&goTypes, "// @intercall type t%d\ntype T%d uint8\n\n", i, i)
		} else {
			fmt.Fprintf(&goTypes, "// @intercall type t%d\ntype T%d []T%d\n\n", i, i, i+1)
		}
	}
	genFile := intercallGeneratedMarker + "\n\npackage synth\n\n" + goTypes.String() +
		"const " + semanticConstantName + " = " + strconv.Quote(base64.RawURLEncoding.EncodeToString(body)) + "\n"
	provFile := "package synth\n\nimport \"context\"\n\n// @intercall procedure find\nfunc Find(ctx context.Context, x T0) error { return nil }\n"
	return map[string]string{"gen.go": genFile, "prov.go": provFile}
}

// metadataShallowModuleFiles renders a marked generated file whose
// shallow head row T0 is uint8 and whose remaining rows form a
// cross-row chain of k declarations T1..Tk: a one-field struct head
// followed by slices, with a final one-field struct. The provider
// takes T0, so the chain is not reached physically; the decoded
// semantic chain from t1 puts its deepest occurrence at depth 2k.
func metadataShallowModuleFiles(t *testing.T, k int) map[string]string {
	t.Helper()
	decls := []string{"type t0 uint8;"}
	decls = append(decls, fmt.Sprintf("type t%d record { f uint8; };", k))
	for i := k - 1; i >= 1; i-- {
		decls = append(decls, fmt.Sprintf("type t%d list t%d;", i, i+1))
	}
	body := metadataBody(t, decls)
	var goTypes strings.Builder
	goTypes.WriteString("// @intercall type t0\ntype T0 uint8\n\n")
	goTypes.WriteString("// @intercall type t" + strconv.Itoa(k) + "\ntype T" + strconv.Itoa(k) + " struct { F uint8 `intercall:\"f\"` }\n\n")
	for i := k - 1; i >= 1; i-- {
		fmt.Fprintf(&goTypes, "// @intercall type t%d\ntype T%d []T%d\n\n", i, i, i+1)
	}
	genFile := intercallGeneratedMarker + "\n\npackage synth\n\n" + goTypes.String() +
		"const " + semanticConstantName + " = " + strconv.Quote(base64.RawURLEncoding.EncodeToString(body)) + "\n"
	provFile := "package synth\n\nimport \"context\"\n\n// @intercall procedure find\nfunc Find(ctx context.Context, x T0) error { return nil }\n"
	return map[string]string{"gen.go": genFile, "prov.go": provFile}
}

// metadataModel runs the complete export model pass over one synthetic
// metadata module.
func metadataModel(t *testing.T, files map[string]string) (*ExportModel, error) {
	t.Helper()
	exp, providers := synthPkg(t, "example.com/synth", files)
	return MapExport(&DiscoverResult{Packages: []*ExplicitPackage{exp}, Providers: providers}, "")
}

func runDeepMetadataSubprocess(t *testing.T) {
	debug.SetMaxStack(deepMaxStackBytes)

	// The reached cross-row chain at exactly 4,096: 2,048 rows plus the
	// parameter root put the deepest physical occurrence at 4,096, and
	// the complete generation is byte-deterministic.
	model, err := metadataModel(t, metadataModuleFiles(t, maxProjectionDepth/2))
	if err != nil {
		t.Fatalf("depth-4096 metadata chain mapping: %v", err)
	}
	goFile, body, err := GenerateExport(model, "exp")
	if err != nil {
		t.Fatalf("depth-4096 metadata chain generation: %v", err)
	}
	deepMustParseGo(t, goFile)
	goFile2, body2, err := GenerateExport(model, "exp")
	if err != nil {
		t.Fatalf("depth-4096 metadata chain generation (second pass): %v", err)
	}
	if !bytes.Equal(goFile, goFile2) || !bytes.Equal(body, body2) {
		t.Fatal("metadata-chain generation at the boundary is not deterministic")
	}

	// One more row exceeds the ceiling; the preflight rejects the
	// reached shape before any recursive mapping or emission, with the
	// stable physical diagnostic.
	_, err = metadataModel(t, metadataModuleFiles(t, maxProjectionDepth/2+1))
	e := depthErrorOf(t, err)
	if !strings.Contains(e.Msg, `type "T2047" exceeds`) {
		t.Fatalf("message %q does not name the deepest row", e.Msg)
	}

	// An unreached cross-row chain of a used generated file sits at
	// exactly 4,096 semantically (2,048 chain rows) and recovers
	// completely.
	if _, err := metadataModel(t, metadataShallowModuleFiles(t, maxProjectionDepth/2)); err != nil {
		t.Fatalf("depth-4096 unreached semantic chain: %v", err)
	}

	// The same unreached chain one declaration deeper exceeds the
	// ceiling; the semantic preflight rejects it at the metadata
	// constant's physical position before any row is projected. The
	// first over-limit occurrence is the final record of the deepest
	// declaration's walk.
	_, err = metadataModel(t, metadataShallowModuleFiles(t, maxProjectionDepth/2+1))
	e = depthErrorOf(t, err)
	if !strings.Contains(e.Msg, "decoded _intercallSemantic: type t2049 exceeds") {
		t.Fatalf("message %q does not name the deepest semantic declaration", e.Msg)
	}
	if e.Filename == "" || e.Pos.Line == 0 {
		t.Fatalf("semantic depth diagnostic has no physical position: %+v", e)
	}
}
