func runDeepImportNamedSubprocess(t *testing.T) {
	debug.SetMaxStack(deepMaxStackBytes)

	src := importNamedChainSource(maxProjectionDepth)
	goFile, body := deepMustGenerate(t, src)
	deepMustParseGo(t, goFile)
	if got := strings.Count(string(body), "type t"); got != maxProjectionDepth {
		t.Fatalf("canonical body has %d type declarations, want %d", got, maxProjectionDepth)
	}
	goFile2, body2 := deepMustGenerate(t, src)
	if !bytes.Equal(goFile, goFile2) || !bytes.Equal(body, body2) {
		t.Fatal("named-chain generation at the boundary is not deterministic")
	}

	badSrc := importNamedChainSource(maxProjectionDepth + 1)
	_, _, err := GenerateImport("deep.intercall", []byte(badSrc), nil, "imp")
	e := depthErrorOf(t, err)
	if !strings.Contains(e.Msg, `type t4096 exceeds`) {
		t.Fatalf("message %q does not name the deepest declaration", e.Msg)
	}
	wantSyntaxDepthPosition(t, e, badSrc, "uint8", 1)
}

