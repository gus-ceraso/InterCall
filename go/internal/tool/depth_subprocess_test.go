func runDeepExportBoundarySubprocess(t *testing.T) {
	debug.SetMaxStack(deepMaxStackBytes)

	// The defined-type chain at exactly 4,096: 2,048 slice
	// declarations with the parameter root put the deepest occurrence
	// at 4,096. The complete export generation — mapping, model,
	// codec, dispatch, and signature emission — runs under the lowered
	// stack and is byte-deterministic.
	model := exportOne(t, "example.com/synth", exportChainPackage(maxProjectionDepth/2))
	goFile, body, err := GenerateExport(model, "exp")
	if err != nil {
		t.Fatalf("depth-4096 defined chain generation: %v", err)
	}
	deepMustParseGo(t, goFile)
	goFile2, body2, err := GenerateExport(model, "exp")
	if err != nil {
		t.Fatalf("depth-4096 defined chain generation (second pass): %v", err)
	}
	if !bytes.Equal(goFile, goFile2) || !bytes.Equal(body, body2) {
		t.Fatal("defined-chain generation at the boundary is not deterministic")
	}

	// The alternating struct/slice chain at exactly 4,096.
	model = exportOne(t, "example.com/synth", exportHybridPackage(maxProjectionDepth/2))
	if _, _, err := GenerateExport(model, "exp"); err != nil {
		t.Fatalf("depth-4096 struct chain generation: %v", err)
	}

	// One more declaration exceeds the ceiling; the preflight rejects
	// the shape before any recursive mapping or emission.
	exportErr(t, "example.com/synth", exportChainPackage(maxProjectionDepth/2+1),
		"exceeds the strict Go projection depth limit of 4096 occurrences")

	// The pure slice parameter chain at exactly 4,097 is rejected the
	// same way.
	exportErr(t, "example.com/synth", exportSlicePackage(maxProjectionDepth),
		"exceeds the strict Go projection depth limit of 4096 occurrences")

	// A deep recursive ring keeps the existing recursive-type
	// diagnostic, and a chain through an unexported type keeps its
	// ordinary exportness error.
	var ring strings.Builder
	ring.WriteString("package synth\n\nimport \"context\"\n\n")
	for i := 0; i < 5000; i++ {
		fmt.Fprintf(&ring, "// @intercall type t%d\ntype T%d []T%d\n\n", i, i, (i+1)%5000)
	}
	ring.WriteString("// @intercall procedure p\nfunc P(ctx context.Context, x T0) error { return nil }\n")
	exportErr(t, "example.com/synth", ring.String(), "recursive type graph")

	var hidden strings.Builder
	hidden.WriteString("package synth\n\nimport \"context\"\n\n// @intercall type t0\ntype T0 t1\n\n")
	for i := 1; i < 5000; i++ {
		fmt.Fprintf(&hidden, "type t%d []t%d\n", i, i+1)
	}
	hidden.WriteString("type t5000 uint8\n")
	hidden.WriteString("// @intercall procedure p\nfunc P(ctx context.Context, x T0) error { return nil }\n")
	exportErr(t, "example.com/synth", hidden.String(), "must be exported")
}

