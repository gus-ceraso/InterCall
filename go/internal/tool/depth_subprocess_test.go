// This file tests the strict Go projection boundary of SPEC.md "Strict
// Go projection depth" through subprocesses that lower the maximum Go
// stack: complete import and export generation succeed at the exact
// 4,096-occurrence ceiling, and every shape one occurrence deeper is
// rejected by the preflight before any recursive processing or Go
// formatting or parsing, with a stable physical source diagnostic.
//
// The shared codec layer registers one codec pair per anonymous type
// occurrence, so a pure list or record chain emits output quadratic in
// the chain length by design and is exercised at the boundary through
// model construction, while the named-interleaved chains — whose
// emission is linear — run the complete generation pipeline at the
// boundary.

// deepMaxStackBytes and deepSubprocessTimeout calibrate the RM-11 and
// RM-13 low-stack boundary subprocesses. The normal build values live in
// depth_budget_test.go; the race build overrides them in
// depth_budget_race_test.go, because the race detector inflates every
// stack frame and slows CPU-bound work, and the boundary subprocesses
// must stay valid under `go test -race`.

// deepSubprocess re-executes the test binary with one environment
// variable set, running only the named test as a subprocess role.
func deepSubprocess(t *testing.T, envVar, testName string) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), deepSubprocessTimeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, os.Args[0], "-test.run=^"+testName+"$")
	cmd.Env = append(os.Environ(), envVar+"=1")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%s subprocess failed: %v\n%s", testName, err, out)
	}
}

// deepMustGenerate fails the subprocess unless the complete import
// generation over src succeeds and returns the generated bytes.
func deepMustGenerate(t *testing.T, src string) (goFile, body []byte) {
	t.Helper()
	goFile, body, err := GenerateImport("deep.intercall", []byte(src), nil, "imp")
	if err != nil {
		t.Fatalf("GenerateImport at the boundary: %v", err)
	}
	return goFile, body
}

// deepMustParseGo fails the subprocess unless the generated bytes parse
// as Go.
func deepMustParseGo(t *testing.T, goFile []byte) {
	t.Helper()
	if _, err := parser.ParseFile(token.NewFileSet(), "binding_gen.go", goFile, parser.AllErrors); err != nil {
		t.Fatalf("generated binding does not parse: %v", err)
	}
}

const deepImportSubprocessEnv = "INTERCALL_RM11_DEEP_IMPORT"

// TestDeepImportProjectionBoundary proves the complete import pipeline
// at the strict Go projection boundary under a lowered stack: pure
// list and record chains at exactly 4,096 occurrences run through
// model construction, the named-interleaved list/record chain at
// exactly 4,096 runs through complete generation and is
// byte-deterministic, the pure shapes at 4,097 are rejected before any
// emission with the stable physical diagnostic, and malformed deep
// input returns an ordinary error.
func TestDeepImportProjectionBoundary(t *testing.T) {
	if os.Getenv(deepImportSubprocessEnv) == "1" {
		runDeepImportBoundarySubprocess(t)
		return
	}
	deepSubprocess(t, deepImportSubprocessEnv, "TestDeepImportProjectionBoundary")
}

func runDeepImportBoundarySubprocess(t *testing.T) {
	debug.SetMaxStack(deepMaxStackBytes)

	// Pure list chain at exactly 4,096: 4,095 lists with the primitive
	// at depth 4,096. Parse, validate, attach, format, and MapImport —
	// override resolution, naming, and codec facts — run under the
	// lowered stack, and the deepest occurrence's Go projection
	// renders 4,095 slice levels.
	listSrc := importListSource(maxProjectionDepth - 1)
	f := mustParseValidate(t, listSrc)
	if _, err := MapImport(f, nil); err != nil {
		t.Fatalf("depth-4096 list model: %v", err)
	}
	m, err := MapImport(mustParseValidate(t, listSrc), nil)
	if err != nil {
		t.Fatalf("depth-4096 list model (second pass): %v", err)
	}
	gt := goTypeOf(f.Decls[0].(*syntax.TypeDecl).Type, m.names, m.types)
	if strings.Count(gt, "[]") != maxProjectionDepth-1 {
		t.Fatalf("deepest Go type renders %d slice levels, want %d", strings.Count(gt, "[]"), maxProjectionDepth-1)
	}

	// Pure record chain at exactly 4,096 through model construction.
	recSrc := importRecordSource(maxProjectionDepth - 1)
	if _, err := MapImport(mustParseValidate(t, recSrc), nil); err != nil {
		t.Fatalf("depth-4096 record model: %v", err)
	}

	// The pure list chain one occurrence deeper is rejected by the
	// preflight before any emission, with the stable physical
	// diagnostic at the exact position of the first over-limit
	// occurrence.
	badList := importListSource(maxProjectionDepth)
	_, _, err = GenerateImport("deep.intercall", []byte(badList), nil, "imp")
	e := depthErrorOf(t, err)
	wantSyntaxDepthPosition(t, e, badList, "uint8", 1)

	// The pure record chain at 4,097 is rejected the same way through
	// the complete pipeline, before any Go formatting of generated
	// content.
	_, _, err = GenerateImport("deep.intercall", []byte(importRecordSource(maxProjectionDepth)), nil, "imp")
	depthErrorOf(t, err)

	// The named-interleaved list/record chain at exactly 4,096 runs the
	// complete generation: 2,048 declarations put the deepest
	// occurrence at 4,096, the shared codec layer emits one linear
	// pair per declaration, and the output is byte-deterministic and
	// parses as Go.
	hybrid := importHybridSource(maxProjectionDepth / 2)
	goFile, body := deepMustGenerate(t, hybrid)
	deepMustParseGo(t, goFile)
	goFile2, body2 := deepMustGenerate(t, hybrid)
	if !bytes.Equal(goFile, goFile2) || !bytes.Equal(body, body2) {
		t.Fatal("boundary generation is not deterministic")
	}

	// Malformed deep input returns an ordinary validation error, never
	// a panic or a depth diagnostic.
	bad := "type t " + strings.Repeat("list ", maxProjectionDepth) + "missing;\n"
	_, _, err = GenerateImport("deep.intercall", []byte(bad), nil, "imp")
	wantErr(t, err, `unresolved type reference "missing"`)
}

