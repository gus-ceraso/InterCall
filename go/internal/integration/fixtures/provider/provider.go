// Echo echoes its input, with mode values that exercise the generated
// exception mapping and failure fallbacks: "denied" returns the denied
// sentinel, "failed" a failed payload, "blank" a zero-field payload,
// "point_failed" a payload holding a named type, "panic" panics,
// "typed_nil" returns a typed-nil payload pointer, "wrapped" returns a
// wrapped error no direct comparison matches, and "bad_utf8" returns a
// success value the encoder rejects. Every mode except the declared
// exceptions selects internal_exception.
// @intercall procedure echo
// @param value The value to echo, or a mode selector.
// @return The unchanged input.
func Echo(ctx context.Context, value string) (string, error) {
	switch value {
	case "denied":
		return "", ErrDenied
	case "failed":
		return "", &Failed{Code: 7, Message: "boom"}
	case "blank":
		return "", &Blank{}
	case "point_failed":
		return "", &PointFailed{Point: Point{X: 1.5, Y: -2.5}}
	case "panic":
		panic("provider panic")
	case "typed_nil":
		var f *Failed
		return "", f
	case "wrapped":
		return "", fmt.Errorf("wrapped: %w", ErrDenied)
	case "bad_utf8":
		return "bad\xff", nil
	}
	return value, nil
}

// Add sums its eight integer arguments.
// @intercall procedure add
func Add(ctx context.Context, a int8, b int16, c int32, d int64, e uint8, f uint16, g uint32, h uint64) (int64, error) {
	return int64(a) + int64(b) + int64(c) + d + int64(e) + int64(f) + int64(g) + int64(h), nil
}

// Measure returns the sum of its float arguments.
// @intercall procedure measure
func Measure(ctx context.Context, x float32, y float64) (float64, error) {
	return float64(x) + y, nil
}

// Sample echoes its byte payload.
// @intercall procedure sample
func Sample(ctx context.Context, data []byte, channel uint8) ([]byte, error) {
	return append([]byte(nil), data...), nil
}

// Wave counts its samples.
// @intercall procedure wave
func Wave(ctx context.Context, samples []uint8) (uint32, error) {
	return uint32(len(samples)), nil
}

// Scale scales a point by a factor.
// @intercall procedure scale
func Scale(ctx context.Context, factor float64, point Point) (Point, error) {
	return Point{X: factor * point.X, Y: factor * point.Y}, nil
}

// Render echoes its pixel list.
// @intercall procedure render
func Render(ctx context.Context, pixels []Pixel, depth uint16) ([]Pixel, error) {
	out := make([]Pixel, len(pixels))
	copy(out, pixels)
	return out, nil
}

// Find returns the tags with the given prefix.
// @intercall procedure find
func Find(ctx context.Context, prefix string, tags []Name) (Names, error) {
	var out Names
	for _, n := range tags {
		if strings.HasPrefix(string(n), prefix) {
			out = append(out, string(n))
		}
	}
	return out, nil
}

