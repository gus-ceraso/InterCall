// Transform copies its matrix rows.
// @intercall procedure transform
func Transform(ctx context.Context, rows Matrix) (Matrix, error) {
	out := make(Matrix, len(rows))
	for i, r := range rows {
		out[i] = append([]int32(nil), r...)
	}
	return out, nil
}

// Paint composes a rectangle from an origin and a color.
// @intercall procedure paint
// @param origin The rectangle origin.
// @param color The rectangle color.
// @return The rectangle size.
func Paint(ctx context.Context, origin struct {
	X int32
	Y int32
}, color struct {
	Red   uint8
	Green uint8
	Blue  uint8
	Alpha uint8
}) (struct {
	Width  uint32
	Height uint32
}, error) {
	return struct {
		Width  uint32
		Height uint32
	}{
		Width:  uint32(origin.X + int32(color.Alpha)),
		Height: uint32(origin.Y + int32(color.Blue)),
	}, nil
}

