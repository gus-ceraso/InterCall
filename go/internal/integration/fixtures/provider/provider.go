// Grid sums the values of its rows.
// @intercall procedure grid
// @param rows The rows to sum.
// @return The sum of the row values.
func Grid(ctx context.Context, rows []struct {
	Origin struct {
		X int16
		Y int16
	}
	Value int64
}) (uint64, error) {
	var sum int64
	for _, r := range rows {
		sum += r.Value
	}
	return uint64(sum), nil
}

