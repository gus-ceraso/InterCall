// Package provider is the shared provider fixture of the end-to-end
// integration tests: tagged providers, reachable ordinary types, and
// application exceptions for the generated export binding in the parent
// fixtures/e2eexport package. Both peers of every test connection run
// the same provider package: the generated dispatch is stateless and
// every provider is goroutine-safe, so the single export binding serves
// any number of connections concurrently, including both ends of one
// connection.
//
// binding_gen.go in fixtures/e2eexport and the owned interface in
// fixtures/interface are generated byte-for-byte from this package
// through the complete intercall-go pipeline; the integration tests
// regenerate both into temporary directories and verify the checked-in
// files never drift.
