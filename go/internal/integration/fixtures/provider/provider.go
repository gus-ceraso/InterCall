// Notify records a message for the tests to observe.
// @intercall procedure notify
// @param message The message to record.
func Notify(ctx context.Context, message string) error {
	notifyMu.Lock()
	notifyMessages = append(notifyMessages, message)
	notifyMu.Unlock()
	return nil
}

// Outer performs one nested call into the peer per unit of depth:
// Outer(0) is 1 and Outer(n) is Inner(n-1) + 1, so the request hops
// from this peer to the opposing peer and back once per level.
// @intercall procedure outer
// @param n The nesting depth.
// @return The nested result.
func Outer(ctx context.Context, n uint64) (uint64, error) {
	if n == 0 {
		return 1, nil
	}
	v, err := e2eimport.Inner(ctx, n-1)
	if err != nil {
		return 0, err
	}
	return v + 1, nil
}

// Inner performs one nested call into the peer per unit of depth:
// Inner(0) is 1 and Inner(n) is Outer(n-1) + 1, so the request hops
// from this peer to the opposing peer and back once per level.
// @intercall procedure inner
// @param n The nesting depth.
// @return The nested result.
func Inner(ctx context.Context, n uint64) (uint64, error) {
	if n == 0 {
		return 1, nil
	}
	v, err := e2eimport.Outer(ctx, n-1)
	if err != nil {
		return 0, err
	}
	return v + 1, nil
}

// Wait blocks until the wait id is released or the handler context is
// canceled, then returns the id.
// @intercall procedure wait
// @param id The wait id.
// @return The released wait id.
func Wait(ctx context.Context, id uint32) (uint32, error) {
	waitMu.Lock()
	ch := waitChans[id]
	if ch == nil {
		ch = make(chan struct{})
		waitChans[id] = ch
	}
	waitMu.Unlock()
	select {
	case <-ch:
		return id, nil
	case <-ctx.Done():
		return 0, ctx.Err()
	}
}

// Test-side synchronization: the wait registry and the notification
// recorder. Both ends of every test connection share this package, so
// every registry and recorder is process-wide and lock-protected.

var (
	waitMu         sync.Mutex
	waitChans      = map[uint32]chan struct{}{}
	notifyMu       sync.Mutex
	notifyMessages []string
)

// ReleaseWait releases one blocked Wait, if any. A second release for
// the same id is a no-op.
func ReleaseWait(id uint32) {
	waitMu.Lock()
	ch := waitChans[id]
	delete(waitChans, id)
	waitMu.Unlock()
	if ch != nil {
		close(ch)
	}
}

// IsWaiting reports whether a Wait with the given id has registered its
// release channel, meaning its handler is blocked or about to block.
func IsWaiting(id uint32) bool {
	waitMu.Lock()
	defer waitMu.Unlock()
	_, ok := waitChans[id]
	return ok
}

// Messages returns a copy of the recorded notifications.
func Messages() []string {
	notifyMu.Lock()
	defer notifyMu.Unlock()
	return append([]string(nil), notifyMessages...)
}

// ResetMessages clears the recorded notifications.
func ResetMessages() {
	notifyMu.Lock()
	notifyMessages = nil
	notifyMu.Unlock()
}
