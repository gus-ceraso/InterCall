import assert from "node:assert/strict";
import { mkdtemp, readFile, symlink, lstat, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { artifactStamp, assertReplaceableInterface, replaceOwnedLeaf, validateOutputDirectory } from "../../dist/cli/ownership.js";

test("writes owned leaves, preserves unchanged bytes, and rejects symlinks", async () => {
    const root = await mkdtemp(join(tmpdir(), "intercall-owner-"));
    const path = join(root, "binding_gen.ts");
    const body = Buffer.from("export const value = 1;\n");
    await replaceOwnedLeaf(path, "import", body);
    const first = await readFile(path);
    assert.match(first.toString(), new RegExp(`sha256:${artifactStamp(body)}`));
    await replaceOwnedLeaf(path, "import", body);
    assert.deepEqual(await readFile(path), first);
    const target = join(root, "target.ts");
    await symlink(path, target);
    await assert.rejects(() => replaceOwnedLeaf(target, "import", body), /replaceable/);
    assert.equal((await lstat(path)).isFile(), true);
    const collision = join(root, "collision");
    await (await import("node:fs/promises")).mkdir(collision);
    await (await import("node:fs/promises")).writeFile(join(collision, "handwritten.ts"), "const x = 1;");
    await assert.rejects(() => validateOutputDirectory(collision), /unowned code/);
    const interfacePath = join(root, "interface.intercall");
    const interfaceBody = "exception internal_exception;\n\nexception invalid_arguments;\n\nexception procedure_not_found;\n";
    const interfaceHeader = `/* Code generated by intercall-ts; artifact sha256:${artifactStamp(interfaceBody)}; DO NOT EDIT. */\n\n`;
    await (await import("node:fs/promises")).writeFile(interfacePath, interfaceHeader + interfaceBody);
    await assertReplaceableInterface(interfacePath);
    const malformedBody = "exception procedure_not_found;\nexception invalid_arguments;\nexception internal_exception;\n";
    const malformedHeader = `/* Code generated by intercall-ts; artifact sha256:${artifactStamp(malformedBody)}; DO NOT EDIT. */\n\n`;
    await (await import("node:fs/promises")).writeFile(interfacePath, malformedHeader + malformedBody);
    await assert.rejects(() => assertReplaceableInterface(interfacePath), /ownership is invalid/);
    await rm(root, { recursive: true, force: true });
});
